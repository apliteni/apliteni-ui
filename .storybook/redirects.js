/** Where an old link should land: the same URL with its story id replaced, or null.
 *  Reads the manager's `?path=/story/<id>` or `/docs/<id>` and the preview's `?id=<id>`. */
export function redirectedSearch(search) {
  const params = new URLSearchParams(search);
  const at = params.get('path')?.match(/^\/(story|docs)\/([^/?#]+)(.*)$/);
  if (at && REDIRECTS[at[2]]) { params.set('path', `/${at[1]}/${REDIRECTS[at[2]]}${at[3]}`); return `?${params}`; }
  const id = params.get('id');
  if (id && REDIRECTS[id]) { params.set('id', REDIRECTS[id]); return `?${params}`; }
  return null;
}
